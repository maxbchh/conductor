-- Conductor: isolated tables for the new cashier app.
-- Public anon access matches the current no-login, single-operator workflow.
-- Do not put personal or payment-card data in these tables.

create table if not exists public.conductor_routes (
  id text primary key,
  name text not null,
  city text not null default 'Тверь',
  stops jsonb not null default '[]'::jsonb,
  fare_per_stop numeric(10,2) not null default 0.50 check (fare_per_stop >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.conductor_vehicles (
  id text primary key,
  number text not null,
  model text not null,
  city text not null default 'Тверь',
  status text not null default 'В эксплуатации',
  previous_status text,
  build_date date,
  routes jsonb not null default '[]'::jsonb,
  note text not null default '',
  updated_at timestamptz not null default now()
);

create table if not exists public.conductor_shifts (
  id text primary key,
  route_id text references public.conductor_routes(id) on delete set null,
  vehicle_id text references public.conductor_vehicles(id) on delete set null,
  game_time text not null default '08:00',
  status text not null default 'open' check (status in ('open','closed')),
  previous_vehicle_status text,
  started_at timestamptz not null default now(),
  ended_at timestamptz
);

create table if not exists public.conductor_tickets (
  ticket_number bigint generated by default as identity primary key,
  shift_id text references public.conductor_shifts(id) on delete set null,
  route_id text references public.conductor_routes(id) on delete set null,
  route_name text not null default '',
  from_stop text not null,
  to_stop text not null,
  stop_count integer not null check (stop_count > 0),
  fare_type text not null check (fare_type in ('Полный','Льготный','Школьный')),
  fare_multiplier numeric(4,2) not null check (fare_multiplier in (0.50,0.75,1.00)),
  fare_per_stop numeric(10,2) not null,
  amount numeric(10,2) not null check (amount >= 0),
  payment_method text not null check (payment_method in ('cash','card')),
  cash_received numeric(10,2) not null default 0,
  change_due numeric(10,2) not null default 0,
  game_time text,
  issued_at timestamptz not null default now()
);

create index if not exists conductor_tickets_shift_idx on public.conductor_tickets(shift_id);
create index if not exists conductor_tickets_issued_idx on public.conductor_tickets(issued_at desc);
create index if not exists conductor_shifts_started_idx on public.conductor_shifts(started_at desc);

alter table public.conductor_routes enable row level security;
alter table public.conductor_vehicles enable row level security;
alter table public.conductor_shifts enable row level security;
alter table public.conductor_tickets enable row level security;

drop policy if exists "Conductor public access routes" on public.conductor_routes;
create policy "Conductor public access routes" on public.conductor_routes for all to anon, authenticated using (true) with check (true);
drop policy if exists "Conductor public access vehicles" on public.conductor_vehicles;
create policy "Conductor public access vehicles" on public.conductor_vehicles for all to anon, authenticated using (true) with check (true);
drop policy if exists "Conductor public access shifts" on public.conductor_shifts;
create policy "Conductor public access shifts" on public.conductor_shifts for all to anon, authenticated using (true) with check (true);
drop policy if exists "Conductor public access tickets" on public.conductor_tickets;
create policy "Conductor public access tickets" on public.conductor_tickets for all to anon, authenticated using (true) with check (true);

grant select, insert, update, delete on public.conductor_routes, public.conductor_vehicles, public.conductor_shifts, public.conductor_tickets to anon, authenticated;
grant usage, select on sequence public.conductor_tickets_ticket_number_seq to anon, authenticated;

-- One-time, non-destructive import of the existing Ticket route and bus data.
-- Existing Ticket tables and records are not modified.
insert into public.conductor_routes (id,name,city,stops,fare_per_stop)
select
  coalesce(nullif(x->>'id',''), 'legacy_route_' || md5(x::text)),
  coalesce(nullif(trim(x->>'name'),''), nullif(trim(x->>'route'),''), 'Без названия'),
  case when lower(coalesce(x->>'city','Тверь')) in ('новоозёрск','новоозерск') then 'Новоозёрск' else 'Тверь' end,
  case when jsonb_typeof(x->'stops')='array' then x->'stops' else '[]'::jsonb end,
  greatest(0,coalesce(nullif(x->>'farePerStop','')::numeric,nullif(x->>'fare_per_stop','')::numeric,0.50))
from public.ticket_shared_state s
cross join lateral jsonb_array_elements(coalesce(s.data->'routes','[]'::jsonb)) x
where s.id='main'
  and coalesce(x->>'transport',x->>'transportType',x->>'type','bus')='bus'
  and not coalesce((s.data->'deletedRouteIds') ? (x->>'id'),false)
on conflict (id) do nothing;

insert into public.conductor_vehicles (id,number,model,city,status,build_date,routes,note)
select
  coalesce(nullif(x->>'id',''), 'legacy_vehicle_' || md5(x::text)),
  coalesce(nullif(x->>'number',''), nullif(x->>'model',''), 'Без номера'),
  coalesce(nullif(x->>'model',''), nullif(x->>'number',''), 'Не указана'),
  case when lower(coalesce(x->>'city','Тверь')) in ('новоозёрск','новоозерск') then 'Новоозёрск' else 'Тверь' end,
  case when x->>'status'='На рейсе' then 'В эксплуатации' else coalesce(nullif(x->>'status',''),'В эксплуатации') end,
  nullif(x->>'buildDate','')::date,
  case when jsonb_typeof(x->'routes')='array' then x->'routes' else '[]'::jsonb end,
  coalesce(x->>'note','')
from public.ticket_shared_state s
cross join lateral jsonb_array_elements(coalesce(s.data->'busDatabase'->'vehicles','[]'::jsonb)) x
where s.id='main'
on conflict (id) do nothing;
